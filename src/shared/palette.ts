import { PET_GEOMETRY } from './constants'

/**
 * 宠物的配色与五官布局。
 *
 * ── 配色方向（一次刻意的改向）──
 *
 * 初版是「暖奶油身体 + 深棕描边 + 粉腮红」，那是这类产品最常见的默认长相：
 * 顺手、安全，也最容易被一眼归进"模板感桌宠"。现在换成：
 *
 * - **主体**：云蓝灰的冷调，带向上的渐变，看起来"被光从上面照着"，
 *   而不是一块平涂。冷调让它在任何壁纸上都**分得开**，
 *   也让暖色（眼睛、腮红）成为画面里唯一的高饱和点。
 * - **描边**：墨蓝而非纯黑或深棕。纯黑在透明窗上显脏，
 *   深棕又把它拉回"毛绒玩具"；墨蓝与冷调主体同源。
 * - **暖色只放在"活的地方"**：眼睛琥珀、腮红藕荷。
 *   整只宠物只有这两处是暖的，于是视线自然落到眼睛上。
 *
 * ── 为什么是常量而不是资源文件 ──
 *
 * v0.1 的默认宠物是**程序化几何角色**（施工令 §4.5），不读图片，
 * 所以颜色必须能被代码直接用。它同时被 `scripts/generate-icons.mjs` 复用，
 * 避免图标与宠物配色漂移。
 */
export const PET_PALETTE = {
  /** 身体主色（上半，受光面）。 */
  bodyTop: 0xe8eef5,
  /** 身体主色（下半，落影面）。与 bodyTop 形成向上的柔和渐变。 */
  bodyBottom: 0xb9c7d9,
  /** 描边：墨蓝。 */
  ink: 0x2f3a4d,
  /**
   * 眼睛：**琥珀**而非纯黑。
   *
   * 纯黑眼睛看起来是"洞"，琥珀看起来是"玻璃珠"——后者才有活物的感觉。
   * 这是整只宠物最关键的单个颜色决定。
   */
  eye: 0xd98a3f,
  /** 瞳孔：比眼睛更深的暖棕，形成虹膜层次。 */
  pupil: 0x3a2416,
  /** 眼白高光（catchlight）：玻璃质感的来源。 */
  catchlight: 0xffffff,
  /** 腮红：藕荷（带一点紫的暖粉），比初版的珊瑚粉更"皮肤"。 */
  blush: 0xe89a9a,
  /** 耳窝内侧：比腮红更淡，避免耳朵抢戏。 */
  earInner: 0xd9a8ab,
  /** 影子：不用纯黑，用与主体暗部同源的冷灰，避免在浅色壁纸上出现"脏斑"。 */
  shadow: 0x2f3a4d,
} as const

